#!/usr/bin/env python3
"""Generic timeline generator for VOX Remotion projects (v2.1 — Community Self-Contained).

Reads a word-timestamps JSON (either ElevenLabs {words:[{t,s,e,sf,ef}]} or
Whisper/edge-tts [{word,start,end}] / {words:[{word,start,end}]}) and writes
a clean `src/timeline.ts` matching WordCue {t, s, e, sf, ef}.

Usage:
    python3 tools/update-timeline.py \
      --input public/audio/vo-timestamps.json \
      --out src/timeline.ts \
      --voice-file audio/vo.mp3 \
      --fps 60 \
      --enable-voice
"""
import argparse
import json
import sys
from pathlib import Path


def normalize_words(raw_data, fps: int):
    raw_words = raw_data["words"] if isinstance(raw_data, dict) else raw_data
    out = []
    for w in raw_words:
        text = w.get("t") or w.get("text") or w.get("word") or ""
        if "s" in w and "e" in w:
            s_ms = int(round(float(w["s"])))
            e_ms = int(round(float(w["e"])))
        else:
            s_sec = float(w.get("start", w.get("startSec", 0.0)))
            e_sec = float(w.get("end", w.get("endSec", s_sec)))
            s_ms = int(round(s_sec * 1000))
            e_ms = int(round(e_sec * 1000))
        sf = int(w["sf"]) if "sf" in w else int(round((s_ms / 1000.0) * fps))
        ef = int(w["ef"]) if "ef" in w else int(round((e_ms / 1000.0) * fps))
        out.append({"t": str(text), "s": s_ms, "e": e_ms, "sf": sf, "ef": ef})
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate src/timeline.ts from word timestamps JSON")
    parser.add_argument("--input", "-i", required=True, help="Path to word timestamps JSON")
    parser.add_argument("--out", "-o", default="src/timeline.ts", help="Output TypeScript path")
    parser.add_argument("--voice-file", default="audio/voiceover.mp3", help="Relative staticFile audio path")
    parser.add_argument("--fps", type=int, default=60, help="Composition FPS (default: 60)")
    parser.add_argument("--beats", type=int, default=7, help="Number of equal fallback beat splits if phaseFrames absent")
    parser.add_argument("--enable-voice", action="store_true", help="Set VOICE_ENABLED = true")
    args = parser.parse_args()

    in_path = Path(args.input)
    if not in_path.exists():
        print(f"ERROR: input JSON not found: {in_path}", file=sys.stderr)
        return 1

    data = json.loads(in_path.read_text(encoding="utf-8"))
    words = normalize_words(data, args.fps)
    if not words:
        print("ERROR: no words found in input JSON", file=sys.stderr)
        return 1

    if isinstance(data, dict) and data.get("recommendedFrames"):
        duration_frames = int(data["recommendedFrames"])
    elif isinstance(data, dict) and data.get("durationSec"):
        duration_frames = int(round(float(data["durationSec"]) * args.fps))
    else:
        duration_frames = max(words[-1]["ef"] + args.fps, args.fps)

    if isinstance(data, dict) and data.get("phaseFrames"):
        phase_frames = [int(x) for x in data["phaseFrames"]]
    else:
        step = duration_frames // max(1, args.beats)
        phase_frames = [i * step for i in range(args.beats)] + [duration_frames]

    beat_titles = (
        data.get("beatTitles")
        if isinstance(data, dict) and data.get("beatTitles")
        else [f"BEAT {i + 1}" for i in range(len(phase_frames) - 1)]
    )

    def esc(s: str) -> str:
        return s.replace("\\", "\\\\").replace('"', '\\"')

    lines = [
        f"// AUTO-GENERATED by tools/update-timeline.py from {in_path.name}",
        "// Re-run with new word timestamps JSON to swap voice without editing scene code.",
        "",
        f"export const FPS = {args.fps};",
        f"export const DURATION_FRAMES = {duration_frames};",
        f"export const PHASE_FRAMES = {phase_frames} as const;",
        f'export const VOICE_FILE = "{esc(args.voice_file)}";',
        f"export const VOICE_ENABLED = {'true' if args.enable_voice else 'false'};",
        "",
        "export interface WordCue {",
        "  t: string;  // word text",
        "  s: number;  // start ms",
        "  e: number;  // end ms",
        "  sf: number; // start frame",
        "  ef: number; // end frame",
        "}",
        "",
        "export const WORD_CUES: WordCue[] = [",
    ]
    for w in words:
        lines.append(
            f'  {{ t: "{esc(w["t"])}", s: {w["s"]}, e: {w["e"]}, sf: {w["sf"]}, ef: {w["ef"]} }},'
        )
    lines.append("];")
    lines.append("")
    lines.append("export const BEAT_TITLES: string[] = [")
    for bt in beat_titles:
        lines.append(f'  "{esc(str(bt))}",')
    lines.append("];")
    lines.append("")

    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"OK: wrote {out_path} ({len(words)} words, {duration_frames} frames @ {args.fps}fps)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
